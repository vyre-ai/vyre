// Writes ui/marks/vyre-art.js from the approved brand files (docs/design/brand/export/vyre). The SVG text is copied as given, never redrawn.
//   node scripts/gen-vyre-mark.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const dir = path.join(root, "docs/design/brand/export/vyre");
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8").trim();
const out = `// Generated by scripts/gen-vyre-mark.mjs from docs/design/brand/export/vyre. Do not edit: the approved marks, copied as given.
export const MASTER = ${JSON.stringify(read("vyre-master.svg"))};
export const SMALL = ${JSON.stringify(read("vyre-small.svg"))};
export const TEMPLATE = ${JSON.stringify(read("vyre-template.svg"))};
`;
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), "../ui/marks/vyre-art.js"), out);
console.log("ui/marks/vyre-art.js written");
