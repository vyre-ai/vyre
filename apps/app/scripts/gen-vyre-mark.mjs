// Writes ui/marks/vyre-art.js: the mark is the icon the site and the app use everywhere (site/favicon.svg, the halftone V on a card with a folded corner, drawn by scripts/gen-mark.mjs).
// The SVG text is copied as given, never redrawn. The glass master stays in docs/design/brand/export/vyre as the brand file.
//   node scripts/gen-vyre-mark.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const dir = path.join(root, "docs/design/brand/export/vyre");
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8").trim();
const icon = fs.readFileSync(path.join(root, "site/favicon.svg"), "utf8").trim();
const out = `// Generated by scripts/gen-vyre-mark.mjs from site/favicon.svg and docs/design/brand/export/vyre. Do not edit: the approved marks, copied as given.
export const MASTER = ${JSON.stringify(icon)};
export const SMALL = ${JSON.stringify(icon)};
export const TEMPLATE = ${JSON.stringify(read("vyre-template.svg"))};
`;
fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), "../ui/marks/vyre-art.js"), out);
console.log("ui/marks/vyre-art.js written");
